"""Level 2: fix a failed GitHub Actions run and open a pull request."""

import shutil

from redtogreen.config import Settings
from redtogreen.github.events import RunInfo
from redtogreen.github.git import clone_at_sha, remote_head
from redtogreen.github.mcp import GitHubOps, open_github
from redtogreen.llm import get_llm
from redtogreen.llm.base import LLM
from redtogreen.pipeline import FixOutcome, new_job_dir, run_agent
from redtogreen.tracing import Tracer
from redtogreen.workspace import Workspace


def pr_body(run: RunInfo, outcome: FixOutcome, job_url: str) -> str:
    files = "\n".join(f"- `{f}`" for f in outcome.changed_files)
    return f"""## RedToGreen fix for a failing CI run

CI run: {run.html_url or run.run_id} on `{run.head_branch}` (commit `{run.head_sha[:7]}`)

{outcome.explanation or "(no explanation given)"}

**Files changed**
{files}

**Checks**
- The full test suite passes in an isolated sandbox (no network, no secrets).
- Test files and CI config were not modified (enforced in code).
- Attempts: {outcome.attempts}, tokens: {outcome.input_tokens + outcome.output_tokens}, cost: ${outcome.cost_usd:.4f}

Trace of every step: {job_url}

> Generated by RedToGreen. A human must review and merge this PR.
"""


async def fix_github_run(run: RunInfo, settings: Settings, job_id: str = "", llm: LLM | None = None,
                         tracer: Tracer | None = None) -> FixOutcome:
    tracer = tracer or Tracer()
    llm = llm or get_llm(settings)
    job_dir = new_job_dir(settings, "gh")
    job_url = f"{settings.public_url.rstrip('/')}/jobs/{job_id}" if job_id else "(CLI run)"
    try:
        async with open_github(settings) as client:
            gh = GitHubOps(client)
            with tracer.span(0, "github", "get_job_logs") as step:
                ci_log = await gh.failed_logs(run.owner, run.repo, run.run_id)
                step.detail = f"{len(ci_log)} chars of CI log"
            with tracer.span(0, "git", "clone") as step:
                clone_at_sha(run.owner, run.repo, run.head_sha, job_dir / "repo", settings.github_token)
                step.detail = f"{run.full_name}@{run.head_sha[:7]}"

            ws = Workspace(job_dir / "repo", settings.protected_paths)
            outcome = await run_agent(ws, settings, llm, tracer, ci_log=ci_log)

            if outcome.status != "fixed":
                if outcome.status == "gave_up" and run.pr_numbers:
                    await gh.comment(run.owner, run.repo, run.pr_numbers[0], (
                        f"RedToGreen could not fix this CI failure after {outcome.attempts} attempt(s).\n\n"
                        f"{outcome.explanation}\n\nTrace: {job_url}"))
                return outcome

            # Race guard: if someone pushed while we worked, our fix is for an old commit.
            with tracer.span(0, "git", "check_branch_head") as step:
                head_now = remote_head(run.owner, run.repo, run.head_branch, settings.github_token)
                step.detail = f"head now {head_now[:7]}, failed run was {run.head_sha[:7]}"
            if head_now != run.head_sha:
                outcome.status = "superseded"
                return outcome

            branch = f"{settings.fix_branch_prefix}run-{run.run_id}"
            title_line = (outcome.explanation.splitlines() or ["fix failing tests"])[0]
            title_line = title_line.removeprefix("Root cause:").strip()[:60] or "fix failing tests"
            with tracer.span(0, "github", "create_branch"):
                await gh.create_branch(run.owner, run.repo, branch, run.head_branch)
            with tracer.span(0, "github", "push_files"):
                await gh.push_files(run.owner, run.repo, branch, outcome.final_files,
                                    f"RedToGreen: fix failing CI run {run.run_id}\n\n{outcome.explanation}")
            with tracer.span(0, "github", "create_pull_request") as step:
                outcome.pr_url = await gh.open_pull_request(
                    run.owner, run.repo, f"RedToGreen: {title_line}", pr_body(run, outcome, job_url),
                    head=branch, base=run.head_branch)
                step.detail = outcome.pr_url
            if run.pr_numbers:
                await gh.comment(run.owner, run.repo, run.pr_numbers[0],
                                 f"RedToGreen opened a fix for the failing CI run: {outcome.pr_url}")
            outcome.status = "pr_opened"
            return outcome
    finally:
        shutil.rmtree(job_dir, ignore_errors=True)


async def run_info_from_api(owner: str, repo: str, run_id: int, settings: Settings) -> RunInfo:
    """CLI mode: look up a run's commit and branch through the GitHub MCP server."""
    async with open_github(settings) as client:
        data = await GitHubOps(client).workflow_run(owner, repo, run_id)
    return RunInfo(
        owner=owner,
        repo=repo,
        run_id=run_id,
        head_sha=data["head_sha"],
        head_branch=data["head_branch"],
        pr_numbers=[pr["number"] for pr in data.get("pull_requests") or [] if "number" in pr],
        workflow_name=data.get("name", ""),
        html_url=data.get("html_url", ""),
    )
